// Generates packages/instruments/src/constants.ts from verified on-chain discovery output.
// Every base58 literal in the repository must originate here (see scripts/guard-no-fabrication.mjs).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib/solana-rpc.mjs";

const u = JSON.parse(readFileSync(join(ROOT, "data", "universe.solana.json"), "utf8"));
const authorities = [...new Set(u.mints.map((m) => m.multiplierAuthority).filter(Boolean))];
const q = (s) => JSON.stringify(s);

const lines = [];
lines.push(`/**
 * Verified on-chain constants. GENERATED by scripts/gen-constants.mjs from data/universe.solana.json.
 * Each mint was proven by getAccountInfo(jsonParsed): owner is Token-2022 and the mint carries scaledUiAmountConfig.
 * Verified at ${u.generatedAt}.
 */

export type VerifiedMint = {
  readonly mint: string;
  readonly symbol: string;
  readonly name: string;
  readonly decimals: number;
  readonly category: "xStocks" | "PreStocks";
  readonly multiplierAuthority: string;
  readonly iconSource: string | null;
};

// https://explorer.solana.com/address/TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb
export const TOKEN_2022_PROGRAM_ID = "TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb";

// https://explorer.solana.com/address/ComputeBudget111111111111111111111111111111
export const COMPUTE_BUDGET_PROGRAM_ID = "ComputeBudget111111111111111111111111111111";

// https://explorer.solana.com/address/MemoSq4gqABAXKb96qnH8TysNcWxMyWCqXgDLGmfcxr
export const MEMO_PROGRAM_ID = "MemoSq4gqABAXKb96qnH8TysNcWxMyWCqXgDLGmfcxr";

// https://explorer.solana.com/address/11111111111111111111111111111111
export const SYSTEM_PROGRAM_ID = "11111111111111111111111111111111";

// https://explorer.solana.com/address/${process.env.COLOPHON_PROGRAM_ID ?? "7pPKsqAg9AFZzSEJbygpbqAVKGFgXpaN5AcqNKrwhCe2"}?cluster=devnet
export const COLOPHON_ANCHOR_PROGRAM_ID = "${process.env.COLOPHON_PROGRAM_ID ?? "7pPKsqAg9AFZzSEJbygpbqAVKGFgXpaN5AcqNKrwhCe2"}";

export const MULTIPLIER_AUTHORITIES: readonly string[] = [`);
for (const a of authorities) lines.push(`  ${q(a)}, // https://explorer.solana.com/address/${a}`);
lines.push(`];

export const ROBINHOOD_CHAIN = {
  mainnetChainId: 4663,
  testnetChainId: 46630,
  mainnetExplorer: "https://robinhoodchain.blockscout.com",
  testnetExplorer: "https://explorer.testnet.chain.robinhood.com",
  uiMultiplierSelector: "0xa60bf13d",
} as const;

// https://robinhoodchain.blockscout.com/address/0x2518853d8a6799734ded70857f0cffc26a175c14
export const UNITSEAL_GUARD_ADDRESS = "0x2518853d8a6799734ded70857f0cffc26a175c14";

export const VERIFIED_SOLANA_MINTS: readonly VerifiedMint[] = [`);
for (const m of u.mints) {
  lines.push(`  // https://explorer.solana.com/address/${m.mint}
  { mint: ${q(m.mint)}, symbol: ${q(m.symbol)}, name: ${q(m.name)}, decimals: ${m.decimals}, category: ${q(m.category)}, multiplierAuthority: ${q(m.multiplierAuthority)}, iconSource: ${q(m.iconSource)} },`);
}
lines.push(`];\n`);
writeFileSync(join(ROOT, "packages", "instruments", "src", "constants.ts"), lines.join("\n"));
process.stderr.write(`constants.ts written: ${u.mints.length} mints, ${authorities.length} authorities\n`);
